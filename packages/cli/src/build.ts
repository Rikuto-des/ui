const HEADER = "// generated by `urushi build` from contracts/ — do not edit\n";

export function sha256(content: string): string {
  return `sha256-${createHash("sha256").update(content).digest("base64")}`;
}

function pascal(jsx: string): string {
  return jsx.replace(/\./g, "");
}

function camel(jsx: string): string {
  const p = pascal(jsx);
  // A leading acronym is lowered whole: OTPInput → otpInput, AlertDialog → alertDialog.
  return p.replace(/^[A-Z]+(?=[A-Z][a-z])|^[A-Z]/, (m) => m.toLowerCase());
}

function schemaOf(part: PartSpec): PartSchema {
  return z.toJSONSchema(part.props, { unrepresentable: "any", io: "input" }) as unknown as PartSchema;
}

function tsType(prop: JsonSchemaProp): string {
  if (prop["x-ts-type"]) return prop["x-ts-type"];
  if (prop.const !== undefined) return JSON.stringify(prop.const);
  if (prop.anyOf) return prop.anyOf.map(tsType).join(" | ");
  if (prop.enum) return prop.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (prop.type) {
    case "string":
      return "string";
    case "boolean":
      return "boolean";
    case "number":
    case "integer":
      return "number";
    default:
      return "unknown";
  }
}

export function emitTypes(contract: Contract): string {
  let out = HEADER;
  const needsReact = contract.parts.some((p) => Object.values(schemaOf(p).properties ?? {}).some((v) => v["x-ts-type"]));
  if (needsReact) out += `import type * as React from "react";\n`;
  for (const part of contract.parts) {
    const schema = schemaOf(part);
    const required = new Set(schema.required ?? []);
    const name = pascal(part.jsx);
    out += `\n/** ${part.description} */\nexport interface ${name}OwnProps {\n`;
    const defaults: Record<string, unknown> = {};
    for (const [key, prop] of Object.entries(schema.properties ?? {})) {
      if (prop.description) out += `  /** ${prop.description} */\n`;
      out += `  ${key}${required.has(key) ? "" : "?"}: ${tsType(prop)};\n`;
      if (prop.default !== undefined) defaults[key] = prop.default;
    }
    out += `}\n`;
    out += `export const ${camel(part.jsx)}Defaults = ${JSON.stringify(defaults)} as const;\n`;
    out += `export const ${camel(part.jsx)}Slot = ${JSON.stringify(part.slot)};\n`;
  }
  return out;
}

function mdEscape(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function emitDoc(contract: Contract): string {
  const lines: string[] = [];
  const title = contract.parts[0].jsx;
  lines.push(`# ${title}`, "", contract.summary, "");
  lines.push(`- Tier: ${contract.tier}`);
  lines.push(`- Rendering: ${typeof contract.rendering === "string" ? contract.rendering : JSON.stringify(contract.rendering)}`);
  lines.push(`- Requires: ${contract.platform.requires.join(", ")}`);
  for (const e of contract.platform.enhances ?? []) lines.push(`- Enhances with ${e.feature} (fallback: ${e.fallback})`);
  lines.push("", "## When to use", "", ...contract.use.map((u) => `- ${u}`), "");
  lines.push("## When not to use", "", ...contract.avoid.map((a) => `- ${a.case} → use \`${a.instead}\``), "");
  lines.push("## Parts", "");
  for (const part of contract.parts) {
    const schema = schemaOf(part);
    const required = new Set(schema.required ?? []);
    lines.push(`### \`<${part.jsx}>\``, "", `${part.description} Renders \`<${part.element} data-slot="${part.slot}">\`.`, "");
    const props = Object.entries(schema.properties ?? {});
    if (props.length) {
      lines.push("| Prop | Type | Default | Description |", "|---|---|---|---|");
      for (const [key, prop] of props) {
        const type = mdEscape(tsType(prop));
        const def = prop.default !== undefined ? `\`${JSON.stringify(prop.default)}\`` : required.has(key) ? "**required**" : "—";
        lines.push(`| \`${key}\` | \`${type}\` | ${def} | ${mdEscape(prop.description ?? "")} |`);
      }
      lines.push("");
    }
    lines.push(
      `className may only adjust: ${part.overrides.length ? part.overrides.join(", ") : "nothing (visuals come from the pack)"}.`,
      "",
    );
  }
  lines.push("## Accessibility", "");
  if (contract.a11y.apg) lines.push(`Pattern: ${contract.a11y.apg}`, "");
  if (contract.a11y.keyboard) {
    lines.push("| Key | Behavior |", "|---|---|");
    for (const [k, v] of Object.entries(contract.a11y.keyboard)) lines.push(`| ${k} | ${mdEscape(v)} |`);
    lines.push("");
  }
  if (contract.a11y.focus) {
    if (contract.a11y.focus.initial) lines.push(`- Initial focus: ${contract.a11y.focus.initial}`);
    if (contract.a11y.focus.restore) lines.push(`- Focus restore: ${contract.a11y.focus.restore}`);
  }
  lines.push(...contract.a11y.rules.map((r) => `- ${r}`), "");
  lines.push("## States", "", contract.states.map((s) => `\`${s}\``).join(", "), "");
  lines.push("## Tokens", "", contract.tokens.map((t) => `\`${t}\``).join(", "), "");
  lines.push("## Examples", "");
  for (const ex of contract.examples) lines.push(`### ${ex.title}`, "", "```tsx", ex.code, "```", "");
  return lines.join("\n");
}

export interface LintPart {
  contract: string;
  slot: string;
  element: string;
  overrides: string[];
  enums: Record<string, string[]>;
  /** prop name → the contract whose root id it must reference, or null for any element. */
  idrefs: Record<string, string | null>;
  /** Set on a contract's root part when it carries the id other parts reference. */
  provides: string | null;
  required: string[];
  /** Every prop the contract declares, so lint messages can point at `title`, `footer`, … */
  props: string[];
  /** HTML attributes the part takes besides the ones every element takes (see partAttributes). */
  attributes: string[];
  /** Attributes every element takes that this part leaves out (`popover` on Menu, `children` on Spinner). */
  omits: string[];
}

export interface PartAttributes {
  /** The attributes every HTML element takes in React's types (`className`, `onClick`, `key`, `ref`, …). */
  common: string[];
  parts: Record<string, Pick<LintPart, "attributes" | "omits">>;
}

export function lintData(contracts: Contract[], attributes?: PartAttributes): Record<string, LintPart> {
  const out: Record<string, LintPart> = {};
  for (const contract of contracts) {
    for (const part of contract.parts) {
      const schema = schemaOf(part);
      const enums: Record<string, string[]> = {};
      const idrefs: Record<string, string | null> = {};
      for (const [key, prop] of Object.entries(schema.properties ?? {})) {
        if (prop.enum) enums[key] = prop.enum;
        if (prop["x-idref"]) idrefs[key] = typeof prop["x-idref"] === "string" ? prop["x-idref"] : null;
      }
      const isRoot = part === contract.parts[0] && "id" in (schema.properties ?? {});
      const props = Object.keys(schema.properties ?? {});
      out[part.jsx] = {
        contract: contract.name,
        slot: part.slot,
        element: part.element,
        overrides: [...part.overrides],
        enums,
        idrefs,
        provides: isRoot ? contract.name : null,
        required: schema.required ?? [],
        props,
        attributes: (attributes?.parts[part.jsx]?.attributes ?? []).filter((n) => !props.includes(n)),
        omits: attributes?.parts[part.jsx]?.omits ?? [],
      };
    }
  }
  return out;
}

/**
 * The props each part takes besides its contract props, read from the component's type
 * in @urushi/react with the TypeScript compiler. That is the HTML attributes of the
 * element its other props go to (`<input>` for Checkbox, not the `<label>` it renders),
 * less the ones the component leaves out (`open` on Dialog), so the lint plugin can
 * report a prop the type checker would reject. Stored as a difference from the
 * attributes every element takes, to keep the lint data small. Names with a `-`
 * (`aria-*`, `data-*`) are left out because TypeScript does not check them either, and
 * so are `__`-prefixed props that parts pass among themselves.
 *
 * typescript comes from the repository root's devDependencies; `urushi build` only
 * runs inside the repository.
 */
export async function partAttributes(root: string, reactPackage: string, names: string[]): Promise<PartAttributes> {
  const { default: ts } = await import("typescript");
  const config = ts.readConfigFile(join(root, "tsconfig.json"), ts.sys.readFile).config;
  // @types/node is not needed to read the components' props, and is the slowest part to load.
  const { options } = ts.parseJsonConfigFileContent({ compilerOptions: { ...config.compilerOptions, types: [] }, files: [] }, ts.sys, root);
  const file = join(reactPackage, "src", "__lint-attributes__.ts");
  const text = [
    `import type * as React from "react";`,
    `import type * as Y from "./index.ts";`,
    `export type Common = React.HTMLAttributes<HTMLElement> & React.RefAttributes<HTMLElement> & React.Attributes;`,
    ...names.map((name, i) => `export type P${i} = React.ComponentProps<typeof Y.${name}>;`),
  ].join("\n");
  const host = ts.createCompilerHost(options);
  const { getSourceFile, fileExists } = host;
  host.getSourceFile = (name, language, ...rest) =>
    name === file ? ts.createSourceFile(name, text, language) : getSourceFile.call(host, name, language, ...rest);
  host.fileExists = (name) => name === file || fileExists.call(host, name);
  const program = ts.createProgram([file], options, host);
  const source = program.getSourceFile(file)!;
  const diagnostics = ts.getPreEmitDiagnostics(program, source);
  if (diagnostics.length) {
    const messages = diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, " "));
    throw new Error(`Could not read the props of the parts in contracts/ from @urushi/react:\n${messages.join("\n")}`);
  }
  const checker = program.getTypeChecker();
  const aliases = source.statements.filter(ts.isTypeAliasDeclaration);
  const propsOf = (alias: (typeof aliases)[number]) =>
    new Set(
      checker
        .getPropertiesOfType(checker.getTypeAtLocation(alias.name))
        .map((p) => p.getName())
        .filter((n) => !n.includes("-") && !n.startsWith("__")),
    );
  const common = propsOf(aliases[0]);
  const parts: PartAttributes["parts"] = {};
  names.forEach((name, i) => {
    const accepted = propsOf(aliases[i + 1]);
    parts[name] = {
      attributes: [...accepted].filter((n) => !common.has(n)).sort(),
      omits: [...common].filter((n) => !accepted.has(n)).sort(),
    };
  });
  return { common: [...common].sort(), parts };
}

