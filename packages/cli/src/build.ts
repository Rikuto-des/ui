type TokenTree = Parameters<typeof flatten>[0];

/** Every token any pack defines, in the first pack's order. */
export function tokenList(packs: Record<string, TokenTree>): TokenInfo[] {
  const tokens = new Map<string, TokenInfo>();
  for (const tree of Object.values(packs)) {
    for (const token of flatten(tree)) {
      const name = varName(token.path);
      const described = describe(tree, token.path);
      const known = tokens.get(name);
      if (known) {
        if (!known.use && described) known.use = described;
        continue;
      }
      tokens.set(name, { name, group: token.path[0], use: TOKEN_USES[name.slice("--ur-".length)] ?? described ?? "" });
    }
  }
  return [...tokens.values()];
}

function describe(tree: TokenTree, path: string[]): string | undefined {
  let node: unknown = tree;
  for (const key of path) node = (node as Record<string, unknown>)?.[key];
  const description = (node as { $description?: unknown })?.$description;
  return typeof description === "string" ? description : undefined;
}

/**
 * The names a module exports, read with patterns. Enough for this repository's
 * entry points, which only use plain `export` statements; `export *` would hide
 * the names, so it is rejected.
 */
export function exportedNames(source: string, file: string): string[] {
  if (/^export\s*\*/m.test(source)) throw new Error(`${file}: list the names instead of \`export *\`, so the lint plugin can check imports`);
  const names = new Set<string>();
  for (const m of source.matchAll(/^export\s+(?:type\s+)?\{([^}]*)\}/gm)) {
    for (const spec of m[1].split(",")) {
      const name = spec.trim().replace(/^type\s+/, "").split(/\s+as\s+/).pop()!.trim();
      if (name) names.add(name);
    }
  }
  for (const m of source.matchAll(/^export\s+(?:declare\s+)?(?:async\s+)?(?:abstract\s+)?(?:function\*?|const|let|var|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm)) {
    names.add(m[1]);
  }
  if (/^export\s+default\b/m.test(source)) names.add("default");
  return [...names].sort();
}

/** Module specifier (`@urushi/react`, `@urushi/react/runtime`, …) → the names it exports. */
export async function packageExports(dir: string): Promise<Record<string, string[]>> {
  const pkg = JSON.parse(await readFile(join(dir, "package.json"), "utf8")) as { name: string; exports: Record<string, string> };
  const out: Record<string, string[]> = {};
  for (const [subpath, target] of Object.entries(pkg.exports)) {
    const specifier = subpath === "." ? pkg.name : `${pkg.name}/${subpath.replace(/^\.\//, "")}`;
    // Expand CSS export patterns into concrete paths for the import validator.
    if (target.includes("*") && target.endsWith(".css")) {
      const folder = join(dir, target.slice(0, target.lastIndexOf("/")));
      for (const file of await readdir(folder)) if (file.endsWith(".css")) out[specifier.replace("*.css", file)] = [];
      continue;
    }
    // A stylesheet is imported for its side effect only.
    out[specifier] = /\.tsx?$/.test(target) ? exportedNames(await readFile(join(dir, target), "utf8"), join(basename(dir), target)) : [];
  }
  return out;
}

