import { readFile, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { createHash } from "node:crypto";

// Offline generation from the pinned, checksummed SVG subset. Never fetch at build time.
const root = resolve(import.meta.dirname, "..");
const assets = join(root, "packages/react/assets/phosphor");
const manifest = JSON.parse(await readFile(join(assets, "manifest.json"), "utf8")) as {
  icons: { name: string; export: string; files: Record<string, { path: string; sha256: string }> }[];
};
const license = (await readFile(join(assets, "LICENSE"), "utf8")).trim();
const banner = `/*! Phosphor Icons — @phosphor-icons/core 2.1.1\n${license}\n*/\n`;
const svgByName = new Map<string, string>();
let source = banner + `// Generated by scripts/build-phosphor-icons.ts. Each export can be tree-shaken.\nimport type { ComponentPropsWithRef, ReactNode } from "react";\n\nexport type IconProps = Omit<ComponentPropsWithRef<"svg">, "children" | "dangerouslySetInnerHTML"> & { size?: 16 | 20 | 24 };\nexport type StatefulIconProps = IconProps & { weight?: "regular" | "fill" };\n\nfunction PhosphorSvg({ size = 20, style, children, ...props }: IconProps & { children: ReactNode }) {\n  const named = Boolean(props["aria-label"] || props["aria-labelledby"]);\n  return <svg width={size} height={size} viewBox="0 0 256 256" fill="currentColor" focusable="false" role={named ? "img" : undefined} aria-hidden={named ? undefined : true} data-slot="icon" {...props} style={{ flexShrink: 0, verticalAlign: "middle", ...style }}>{children}</svg>;\n}\n\n`;
for (const icon of manifest.icons) {
  const bodies: Record<string, string> = {};
  for (const [weight, file] of Object.entries(icon.files)) {
    const svg = await readFile(join(assets, file.path), "utf8");
    if (createHash("sha256").update(svg).digest("hex") !== file.sha256) throw new Error(`SVG checksum mismatch: ${file.path}`);
    if (!/^<svg\b[^>]*viewBox="0 0 256 256"[^>]*>[\s\S]*<\/svg>\s*$/.test(svg) || /<(script|foreignObject|image)\b|\bon\w+=|href=/.test(svg)) throw new Error(`Unexpected SVG: ${file.path}`);
    if (weight === "regular") svgByName.set(icon.name, svg);
    bodies[weight] = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/([a-z]+)-([a-z]+)=/g, (_, a: string, b: string) => a + b[0].toUpperCase() + b.slice(1) + "=");
  }
  const stateful = Boolean(bodies.fill);
  source += `export function ${icon.export}(${stateful ? '{ weight = "regular", ...props }: StatefulIconProps' : 'props: IconProps'}) {\n  return <PhosphorSvg data-phosphor="${icon.name}"${stateful ? ' data-weight={weight}' : ''} {...props}>${stateful ? `{weight === "fill" ? <>${bodies.fill}</> : <>${bodies.regular}</>}` : bodies.regular}</PhosphorSvg>;\n}\n\n`;
}
await writeFile(join(root, "packages/react/src/icons.tsx"), source);
const cssPath = join(root, "packages/react/styles/index.css");
let css = await readFile(cssPath, "utf8");
css = css.replace(/\/\*! Phosphor Icons[\s\S]*?\*\/\n/, "");
css = css.replace(/\/\* phosphor:([a-z-]+) \*\/\s*url\("[^"]*"\)/g, (_, name: string) => {
  const svg = svgByName.get(name);
  if (!svg) throw new Error(`Unknown CSS icon: ${name}`);
  return `/* phosphor:${name} */ url("data:image/svg+xml,${encodeURIComponent(svg.trim())}")`;
});
await writeFile(cssPath, banner + css);
console.log(`Phosphor: generated ${manifest.icons.length} icon exports and component masks from pinned SVGs.`);
